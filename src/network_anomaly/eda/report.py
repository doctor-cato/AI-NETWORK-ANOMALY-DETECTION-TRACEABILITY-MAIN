def _number(value, digits: int = 2) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, int):
        return f"{value:,}"
    return f"{value:,.{digits}f}"


def _percent(part, whole, digits: int = 4) -> str:
    if not whole:
        return "n/a"
    return f"{part / whole * 100:.{digits}f}%"


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def _join_columns(columns) -> str:
    return ", ".join(f"`{column}`" for column in columns)


def render_report(summary: dict, figures: list[dict], context: dict) -> str:
    """Return the Markdown EDA report."""
    sections = [
        _header_section(summary, context),
        _overview_section(summary, context),
        _target_section(summary),
        _quality_section(summary),
        _feature_section(summary),
        _relationship_section(summary, figures),
        _boundary_section(context["leakage_boundary"]),
        _readiness_section(context["readiness"], context),
        _limitations_section(summary, context),
    ]
    return "\n\n".join(section.strip() for section in sections) + "\n"


