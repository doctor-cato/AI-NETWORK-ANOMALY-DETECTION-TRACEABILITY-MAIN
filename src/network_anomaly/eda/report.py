def _boundary_section(boundary: dict) -> str:
    permitted = "\n".join(f"- {item}" for item in boundary["permitted_now"])
    forbidden = "\n".join(f"- {item}" for item in boundary["not_permitted_now"])
    split = boundary["split_manifest"]
    split_detail = str(split.get("detail", "")).strip()
    split_table = _table(
        ["Item", "Status"],
        [
            ["Verified train/validation/test split", str(split["status"])],
            ["Expected split manifest path", f"`{split['path']}`"],
            ["Leakage audit on real partitions", NOT_VERIFIED],
            ["Train-only fitted preprocessing artifact", NOT_VERIFIED],
        ],
    )
    return f"""## 7. Leakage-safe EDA boundary

Issue #6 and Issue #7 reference each other: the EDA needs to know which data may be
used for design decisions, and the split protocol needs the EDA findings to define the
handling policy. This run resolves that ordering **without** assuming a split that does
not exist.

### Split status

{split_table}

{split_detail}

### Permitted in this run

{permitted}

### Not permitted in this run

{forbidden}

### Consequence for the findings

Every observation in this report is a property of the source population. It is a valid
input for a design discussion, but it is **not** a train-only decision. Accordingly:

- No feature is selected, dropped or ranked by this report.
- No imputer, encoder, scaler, selector, resampler or threshold is fitted.
- No claim is made that cross-split leakage has been checked.
- No undocumented random split was created to work around the missing split.
- No row was removed on the basis of its label or of its duplicate status.

All train-dependent recommendations are therefore marked `{PENDING_SPLIT}`."""


