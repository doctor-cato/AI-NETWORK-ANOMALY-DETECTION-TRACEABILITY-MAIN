def _target_section(summary: dict) -> str:
    labels = summary["label_counts"]
    attacks = summary["attack_counts"]
    rows = summary["rows"]
    benign = labels.get("0", 0)
    attack = labels.get("1", 0)
    majority = max(benign, attack)
    minority = min(benign, attack)
    label_table = _table(
        ["Label", "Flows", "Share"],
        [
            ["0 (Benign)", _number(benign), _percent(benign, rows)],
            ["1 (Attack)", _number(attack), _percent(attack, rows)],
        ],
    )
    attack_table = _table(
        ["Attack category", "Flows", "Share"],
        [
            [name, _number(count), _percent(count, rows)]
            for name, count in sorted(attacks.items(), key=lambda item: -item[1])
        ],
    )
    rare = sorted(attacks.items(), key=lambda item: item[1])[:3]
    rare_text = ", ".join(f"`{name}` ({count:,} rows)" for name, count in rare)
    return f"""## 3. Target distribution

All counts below are `EXECUTED ON REAL DATA` over the full population of
{_number(rows)} rows.

### Binary target `Label`

{label_table}

Majority/minority ratio: **{majority / minority:.2f}:1** ({_number(majority)} benign
against {_number(attack)} attack flows, {_percent(majority, rows)} against
{_percent(minority, rows)}).

### Multiclass target `Attack`

{attack_table}

The three rarest categories are {rare_text}. `Worms` is the rarest class in the dataset.

### Interpretation of the imbalance risk

- A default classifier that predicts the majority class already reaches
  {_percent(majority, rows)} accuracy. Accuracy is therefore not a meaningful metric
  for this dataset; the evaluation plan has to report per-category recall and a
  macro-averaged score instead.
- The rare categories are far too small to support a stable per-class model on their
  own. `Worms` has {attacks.get('Worms', 0)} rows in total, so a single split that
  distributes it across partitions can leave one or two partitions without a single
  example.
- Stratification, resampling and threshold selection therefore have to be decided on
  the training partition only, and the decision has to be recorded with the split
  identifier. Choosing a strategy that looks at the full label distribution would leak
  test information.
- The rarest categories are also the categories most exposed to the duplicate findings
  in section 4, because deduplication strategies that keep the first occurrence change
  rare-class counts the most."""


def _quality_section(summary: dict) -> str:
    statistics = summary["numeric_statistics"]
    quality_columns = [
        column
        for column, values in statistics.items()
        if values["unavailable_count"] or values["negative_value_count"]
    ]
    quality_rows = []
    for column in quality_columns:
        values = statistics[column]
        tokens = values["token_counts"]
        quality_rows.append(
            [
                f"`{column}`",
                _number(tokens.get("blank", 0)),
                _number(tokens.get("nan_literal", 0)),
                _number(tokens.get("null_literal", 0)),
                _number(tokens.get("positive_infinity", 0)),
                _number(tokens.get("negative_infinity", 0)),
                _number(tokens.get("invalid_numeric", 0)),
            ]
        )
    if quality_rows:
        quality_table = _table(
            ["Column", "blank", "NaN", "null", "+Inf", "-Inf", "invalid"], quality_rows
        )
    else:
        quality_table = "No column contains a missing, non-finite or invalid numeric token."
    duplicates = summary["duplicates"]
    exact = duplicates["exact_full_row"]
    source = duplicates["source_feature"]
    ml = duplicates["ml_feature_equivalent"]
    behavioral = duplicates["behavioral_v1"]
    duplicate_table = _table(
        ["Fingerprint scope", "Distinct rows", "Repeated rows"],
        [
            [
                "Exact full row (55 columns)",
                _number(exact["distinct_rows"]),
                _number(exact["duplicate_rows"]),
            ],
            [
                "Source feature (53 columns, targets excluded)",
                _number(source["distinct_rows"]),
                _number(source["duplicate_rows"]),
            ],
            [
                "ML-feature equivalent (47 columns)",
                _number(ml["distinct_rows"]),
                _number(ml["duplicate_rows"]),
            ],
            [
                "Behavioral-v1 (47 columns, separate namespace)",
                _number(behavioral["distinct_rows"]),
                _number(behavioral["duplicate_rows"]),
            ],
        ],
    )
    group_table = _table(
        ["Scope", "Groups with duplicates"],
        [
            ["Exact full row", _number(exact["groups_with_duplicates"])],
            ["ML-feature equivalent", _number(ml["groups_with_duplicates"])],
        ],
    )
    conflict_table = _table(
        ["Conflict", "Groups", "Rows"],
        [
            [
                "Binary `Label` conflict (0 and 1 in one group)",
                _number(ml["binary_label_conflict_groups"]),
                _number(ml["rows_in_binary_label_conflict_groups"]),
            ],
            [
                "Multiple `Attack` categories in one group",
                _number(ml["multiple_attack_category_groups"]),
                _number(ml["rows_in_multiple_attack_category_groups"]),
            ],
            [
                "`Benign` mixed with a malicious category",
                _number(ml["benign_attack_conflict_groups"]),
                _number(ml["rows_in_benign_attack_conflict_groups"]),
            ],
        ],
    )
    contingency = summary["duration_throughput"]["population"]
    contingency_table = _table(
        ["duration_zero / rate_non_finite / throughput_non_finite", "Flows"],
        [[key.replace(",", ", "), _number(value)] for key, value in sorted(contingency.items())],
    )
    zero_and_rate = contingency.get(
        "duration_zero=True,rate_non_finite=True,throughput_non_finite=False", 0
    )
    zero_without_rate = contingency.get(
        "duration_zero=True,rate_non_finite=False,throughput_non_finite=False", 0
    )
    return f"""## 4. Data quality

### Missing, blank and non-finite tokens

Token classes are counted separately so that a blank cell, a literal `NaN`, a positive
infinity, a negative infinity and an invalid numeric token never collapse into one
number. The counters come from the streaming pass of
`scripts/validate_data.py` and from the token refinement pass of this EDA run.

{quality_table}

Columns without any entry in this table contain only finite, non-negative values. No
row of the source file was modified, normalised or rewritten.

### Zero and near-zero flow durations

The two rate fields (`SRC_TO_DST_SECOND_BYTES`, `DST_TO_SRC_SECOND_BYTES`) carry the
non-finite values; the two average-throughput fields (`SRC_TO_DST_AVG_THROUGHPUT`,
`DST_TO_SRC_AVG_THROUGHPUT`) are finite on every row. The contingency table below
cross-tabulates the published duration with the non-finite rate and throughput state.

{contingency_table}

{_number(zero_and_rate)} flows have a zero published duration and a non-finite rate
value, while {_number(zero_without_rate)} flows have a zero duration and a finite rate
value. The non-finite rate values therefore occur **only** on zero-duration flows.

This is an **association observed in the published bytes**. The feature dictionary does
not expose the producer arithmetic, so this report does **not** claim that a division by
zero caused the infinities, and it does not treat the association as a causal relation.
The affected rows are kept, not dropped: the approved handling policy
(`docs/NF_UNSW_NB15_V3_PREPROCESSING_POLICY.md`) keeps zero-duration flows as a separate
observed condition and forbids replacing infinity with zero silently.

### Duplicate rows

{duplicate_table}

Groups holding more than one row:

{group_table}

Label conflicts inside repeated groups:

{conflict_table}

The behavioral-v1 fingerprint uses the same ordered 47 columns as the ML baseline under a
separate namespace, so its equivalence classes and counts coincide with the
ML-feature-equivalent row by construction of the v3 contract.

### Why repeated rows must not be deleted automatically

1. **A repeat is not automatically a redundant copy.** NetFlow exporters emit one record
   per observed flow, and a legitimate network conversation can produce several records
   with an identical feature vector. Removing them would delete observed traffic, not
   duplicated bytes.
2. **Deletion is label-dependent.** The affected rows are not label-neutral: attack
   categories are concentrated in specific groups, and the rarest categories are the
   ones that lose the most rows. A deduplication rule that keeps the first occurrence
   silently changes the class distribution that the model will be trained on.
3. **The correct treatment is a split-time decision.** The v3 protocol requires the
   duplicate and leakage fingerprints to be computed and audited *before* partition
   assignment, so that a repeated observation cannot straddle two partitions. Deciding
   how to consolidate a group is a modelling decision that has to be taken on the
   training partition and recorded in the split manifest.
4. **The evidence must stay inspectable.** Until a split exists, the raw rows are the
   only evidence available; an automatic delete would destroy the ability to quantify
   the effect of the decision later.

For the same reason this report contains no deduplicated, resampled or re-labelled
derivative of the source file."""


def _feature_section(summary: dict) -> str:
    statistics = summary["numeric_statistics"]
    quantiles = summary["quantiles"]
    shape = summary["sample_statistics"]
    selected = [
        "IN_BYTES",
        "OUT_BYTES",
        "IN_PKTS",
        "OUT_PKTS",
        "FLOW_DURATION_MILLISECONDS",
        "SRC_TO_DST_AVG_THROUGHPUT",
        "DST_TO_SRC_AVG_THROUGHPUT",
        "MIN_TTL",
        "MAX_TTL",
        "LONGEST_FLOW_PKT",
        "TCP_WIN_MAX_OUT",
    ]
    rows = []
    for column in selected:
        values = statistics[column]
        quant = quantiles.get(column, {})
        zero_share = (
            _percent(values["zero_count"], values["finite_count"])
            if values["finite_count"]
            else "n/a"
        )
        rows.append(
            [
                f"`{column}`",
                _number(values["minimum"]),
                _number(values["maximum"]),
                _number(values["mean"]),
                _number(quant.get("p50")),
                _number(values["standard_deviation"]),
                _number(quant.get("p95")),
                zero_share,
            ]
        )
    feature_table = _table(
        ["Feature", "min", "max", "mean", "p50", "std", "p95", "zero share"], rows
    )
    constant = [column for column, values in shape.items() if values.get("constant")]
    constant_text = ", ".join(f"`{column}`" for column in constant) if constant else "none"
    heavy = sorted(
        (
            (column, values["skewness"], values["excess_kurtosis"])
            for column, values in shape.items()
            if values["skewness"] is not None
        ),
        key=lambda item: -abs(item[1]),
    )[:8]
    heavy_table = _table(
        ["Feature", "skewness (sample)", "excess kurtosis (sample)", "reading"],
        [
            [
                f"`{column}`",
                _number(skew, 3),
                _number(kurtosis, 3),
                "right-skewed" if skew > 1 else ("left-skewed" if skew < -1 else "moderate"),
            ]
            for column, skew, kurtosis in heavy
        ],
    )
    return f"""## 5. Feature distributions

Population statistics (minimum, maximum, mean, standard deviation, zero count) are
`EXECUTED ON REAL DATA` over every finite row. The quantiles are **exact population
quantiles**: the values are buffered on disk while streaming and sorted afterwards, so
they are not sample estimates. Skewness and kurtosis are `SAMPLE-BASED` because they are
computed from the seeded reservoir sample.

### Descriptive statistics of the headline quantitative features

{feature_table}

### Shape of the distribution

{heavy_table}

The dominant pattern is a zero-heavy, strongly right-skewed distribution: most flows
carry no payload, and a small number of flows carry very large byte counts. The
consequences for modelling are:

- A linear model on raw byte counts would be dominated by a handful of large flows.
  A log1p or a training-derived robust scaling is therefore likely to be needed, but
  the transform is a train-only decision and stays `{PENDING_SPLIT}`.
- Heavy tails inflate the standard deviation, so a median-based imputation baseline is
  safer than a mean-based one for the skewed byte and duration fields.
- `IN_BYTES` and `OUT_BYTES` and their packet counterparts are strongly zero-inflated.
  Whether a zero means "no payload" or "not observed" is a semantic question about the
  exporter, not something the data can answer.

### Constant and near-constant features

Constant features detected on the real data: {constant_text}.
A feature is reported as constant when the sample variance is zero, and as near-constant
when the inter-quartile range collapses to zero while the extremes still differ. Both
conditions are evaluated on the observed values, not assumed from the schema.

### Outliers and transformation risk

The maximum values are orders of magnitude above the 95th percentile for the byte,
packet and duration fields, which is the quantitative form of the heavy-tail finding
above. The baseline contract does not clip or winsorise: any clipping bound is a
training-derived decision that has to be justified on validation data and recorded with
the affected row counts, and it is not part of this EDA."""


