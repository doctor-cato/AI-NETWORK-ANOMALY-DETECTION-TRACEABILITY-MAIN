def verify_report_consistency(
    report_path: Path,
    manifest_path: Path,
) -> bool:
    """Verify that report text fields match manifest and constants (consistency check only)."""
    if not manifest_path.is_file():
        print(f"[smoke-report] FAIL: Companion manifest not found: {manifest_path}")
        return False
    if not report_path.is_file():
        print(f"[smoke-report] FAIL: Report file not found: {report_path}")
        return False

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[smoke-report] FAIL: Cannot parse companion manifest: {e}")
        return False

    report_text = report_path.read_text(encoding="utf-8")

    errors = []
    recorded_sm = manifest.get("split_manifest_sha256")
    if not recorded_sm or f"`{recorded_sm}`" not in report_text:
        errors.append("split_manifest_sha256 mismatch or missing in report")

    recorded_art = manifest.get("artifact_sha256")
    if not recorded_art or f"`{recorded_art}`" not in report_text:
        errors.append("artifact_sha256 mismatch or missing in report")

    if f"`{PREPROCESSING_POLICY_VERSION}`" not in report_text:
        errors.append(f"preprocessing_policy_version '{PREPROCESSING_POLICY_VERSION}' missing")

    if f"`{FEATURE_CONTRACT_VERSION}`" not in report_text:
        errors.append(f"feature_contract_version '{FEATURE_CONTRACT_VERSION}' missing")

    if f"`{SPLIT_PROTOCOL_VERSION}`" not in report_text:
        errors.append(f"split_protocol_version '{SPLIT_PROTOCOL_VERSION}' missing")

    if "without loading joblib" in report_text:
        errors.append("Report improperly claims verification 'without loading joblib'")

    if errors:
        for err in errors:
            print(f"[smoke-report] FAIL (CONSISTENCY): {err}")
        return False

    print(
        "[smoke-report] PASS (CONSISTENCY ONLY): Report text aligns with companion manifest "
        "and canonical constants."
    )
    print(
        "[smoke-report] Scope Notice: This check verifies Markdown consistency and manifest "
        "syntax only. It does NOT verify raw dataset bytes, file presence, or real-data "
        "execution evidence."
    )
    return True


def generate_smoke_report(
    report_path: Path = DEFAULT_REPORT_PATH,
    manifest_path: Path = DEFAULT_MANIFEST_PATH,
    artifact_path: Path = DEFAULT_ARTIFACT_PATH,
    split_manifest_path: Path = DEFAULT_SPLIT_MANIFEST_PATH,
    dataset_path: Path = DEFAULT_DATASET_PATH,
    evidence_path: Path = DEFAULT_EVIDENCE_PATH,
    check_report_consistency: bool = False,
    verify_real_data: bool = False,
    expected_dataset_sha256: str = EXPECTED_DATASET_SHA256,
) -> bool:
    """Generate or verify real-data smoke evidence report with fail-closed checks."""
    if check_report_consistency:
        return verify_report_consistency(report_path, manifest_path)

    # 1. Real-data verification: all 5 sources MUST be present on disk (Finding P2-A)
    required_files = {
        "Raw dataset CSV": dataset_path,
        "Split manifest JSON": split_manifest_path,
        "Preprocessor artifact (.joblib)": artifact_path,
        "Companion manifest JSON": manifest_path,
        "Execution evidence JSON": evidence_path,
    }
    missing = [f"{name} ({path})" for name, path in required_files.items() if not path.is_file()]
    if missing:
        print(
            f"[smoke-report] FAIL: Real-data verification requires all files on disk. "
            f"Missing: {', '.join(missing)}"
        )
        return False

    # 2. Read and parse manifests and execution evidence
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[smoke-report] FAIL: Cannot read companion manifest: {e}")
        return False

    try:
        split_manifest = json.loads(split_manifest_path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[smoke-report] FAIL: Cannot read split manifest: {e}")
        return False

    try:
        evidence = json.loads(evidence_path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[smoke-report] FAIL: Cannot read execution evidence: {e}")
        return False

    # 3. Compute SHA-256 directly from disk bytes (Finding P2-B)
    print("[smoke-report] Computing SHA-256 directly from file bytes on disk...")
    actual_ds_sha256 = _sha256_file(dataset_path)
    actual_sm_sha256 = _sha256_file(split_manifest_path)
    actual_art_sha256 = _sha256_file(artifact_path)

    # 4. Cross-check hashes against manifests, evidence, and constants
    if actual_ds_sha256 != expected_dataset_sha256:
        print(
            f"[smoke-report] FAIL: Raw dataset SHA-256 mismatch with expected constant: "
            f"disk={actual_ds_sha256}, expected={expected_dataset_sha256}"
        )
        return False

    if manifest.get("dataset_sha256") != actual_ds_sha256:
        print(
            f"[smoke-report] FAIL: Dataset SHA-256 mismatch with companion manifest: "
            f"disk={actual_ds_sha256}, manifest={manifest.get('dataset_sha256')}"
        )
        return False

    if split_manifest.get("dataset_sha256") != actual_ds_sha256:
        print(
            f"[smoke-report] FAIL: Dataset SHA-256 mismatch with split manifest: "
            f"disk={actual_ds_sha256}, split_manifest={split_manifest.get('dataset_sha256')}"
        )
        return False

    if actual_sm_sha256 != manifest.get("split_manifest_sha256"):
        print(
            f"[smoke-report] FAIL: Split manifest SHA-256 mismatch: "
            f"disk={actual_sm_sha256}, companion_manifest={manifest.get('split_manifest_sha256')}"
        )
        return False

    if actual_art_sha256 != manifest.get("artifact_sha256"):
        print(
            f"[smoke-report] FAIL: Artifact SHA-256 mismatch: "
            f"disk={actual_art_sha256}, companion_manifest={manifest.get('artifact_sha256')}"
        )
        return False

    # Canonical constants verification
    prep_policy_ver = manifest.get("preprocessing_policy_version")
    if prep_policy_ver != PREPROCESSING_POLICY_VERSION:
        print(
            f"[smoke-report] FAIL: Preprocessing policy version mismatch: "
            f"manifest={prep_policy_ver}, canonical={PREPROCESSING_POLICY_VERSION}"
        )
        return False

    feat_contract_ver = manifest.get("feature_contract_version")
    if feat_contract_ver != FEATURE_CONTRACT_VERSION:
        print(
            f"[smoke-report] FAIL: Feature contract version mismatch: "
            f"manifest={feat_contract_ver}, canonical={FEATURE_CONTRACT_VERSION}"
        )
        return False

    split_protocol_ver = manifest.get("split_protocol_version")
    if split_protocol_ver != SPLIT_PROTOCOL_VERSION:
        print(
            f"[smoke-report] FAIL: Split protocol version mismatch: "
            f"manifest={split_protocol_ver}, canonical={SPLIT_PROTOCOL_VERSION}"
        )
        return False

    # 5. Fail-closed pre-deserialization integrity check
    art_verify = verify_preprocessing_artifact(
        artifact_path=artifact_path,
        manifest_path=manifest_path,
        split_manifest_path=split_manifest_path,
        dataset_path=dataset_path,
        expected_dataset_sha256=actual_ds_sha256,
    )
    if art_verify["status"] != "PASS":
        print(f"[smoke-report] FAIL: Artifact verification failed: {art_verify['errors']}")
        return False

    # 6. Validate execution claims against execution evidence (Finding P2-C)
    if not isinstance(evidence, dict):
        print("[smoke-report] FAIL: Execution evidence is not a valid JSON dictionary")
        return False

    # Check fit and transform evidence
    fit_ev = evidence.get("fit_and_transform")
    if not fit_ev or fit_ev.get("status") != "PASS":
        print("[smoke-report] FAIL: Execution evidence missing successful 'fit_and_transform'")
        return False

    partitions = fit_ev.get("partitions", {})
    for part in ("train", "validation", "test"):
        if part not in partitions:
            print(f"[smoke-report] FAIL: Execution evidence missing partition '{part}'")
            return False
        if not partitions[part].get("all_finite"):
            print(f"[smoke-report] FAIL: Execution evidence partition '{part}' is not all finite")
            return False
        if not partitions[part].get("zero_duration_retained"):
            print(f"[smoke-report] FAIL: Zero duration not retained in '{part}'")
            return False

    # Check verify-only evidence
    verify_ev = evidence.get("verify_only")
    if not verify_ev or verify_ev.get("status") != "PASS":
        print("[smoke-report] FAIL: Execution evidence missing successful 'verify_only'")
        return False
    if verify_ev.get("exit_code") != 0:
        print(f"[smoke-report] FAIL: verify_only exit code non-zero: {verify_ev.get('exit_code')}")
        return False

    # Check reproducibility evidence
    repro_ev = evidence.get("check_reproducibility")
    if not repro_ev or repro_ev.get("status") != "PASS":
        print("[smoke-report] FAIL: Execution evidence missing successful 'check_reproducibility'")
        return False
    if not repro_ev.get("parameters_identical") or not repro_ev.get("outputs_identical"):
        print("[smoke-report] FAIL: Reproducibility check reported divergence between passes")
        return False

    # Cross-check evidence recorded hashes with actual disk hashes
    if evidence.get("dataset_sha256") and evidence.get("dataset_sha256") != actual_ds_sha256:
        print(
            f"[smoke-report] FAIL: Evidence dataset_sha256 mismatch: "
            f"{evidence.get('dataset_sha256')}"
        )
        return False

    if (
        evidence.get("split_manifest_sha256")
        and evidence.get("split_manifest_sha256") != actual_sm_sha256
    ):
        print("[smoke-report] FAIL: Evidence split_manifest_sha256 mismatch")
        return False

    if evidence.get("artifact_sha256") and evidence.get("artifact_sha256") != actual_art_sha256:
        print("[smoke-report] FAIL: Evidence artifact_sha256 mismatch")
        return False

    # 7. Build report content strictly populated from verified evidence
    dataset_bytes = dataset_path.stat().st_size
    content = build_report_text(
        evidence=evidence,
        dataset_path=dataset_path,
        dataset_sha256=actual_ds_sha256,
        dataset_bytes=dataset_bytes,
        split_protocol_ver=split_protocol_ver,
        split_manifest_path=split_manifest_path,
        actual_sm_sha256=actual_sm_sha256,
        prep_policy_ver=prep_policy_ver,
        feat_contract_ver=feat_contract_ver,
        artifact_path=artifact_path,
        actual_art_sha256=actual_art_sha256,
        manifest_path=manifest_path,
    )

    if verify_real_data:
        if not report_path.is_file():
            print(f"[smoke-report] FAIL: Report does not exist: {report_path}")
            return False
        existing = report_path.read_text(encoding="utf-8")
        if existing.strip() != content.strip():
            print("[smoke-report] FAIL: Existing report text diverges from verified evidence")
            return False
        print(
            "[smoke-report] REAL-DATA VERIFIED: existing report strictly matches all "
            "on-disk artifacts and execution evidence."
        )
        return True

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(content, encoding="utf-8")
    print(
        "[smoke-report] REAL-DATA VERIFIED: all 5 artifacts verified on disk with "
        "matching execution evidence."
    )
    print(f"[smoke-report] Generated {report_path} with verified provenance and evidence.")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--report-path",
        type=Path,
        default=DEFAULT_REPORT_PATH,
        help="Path to REAL_DATA_SMOKE_REPORT.md",
    )
    parser.add_argument(
        "--manifest-path",
        type=Path,
        default=DEFAULT_MANIFEST_PATH,
        help="Path to preprocessing manifest JSON",
    )
    parser.add_argument(
        "--artifact-path",
        type=Path,
        default=DEFAULT_ARTIFACT_PATH,
        help="Path to preprocessor .joblib artifact",
    )
    parser.add_argument(
        "--split-manifest-path",
        type=Path,
        default=DEFAULT_SPLIT_MANIFEST_PATH,
        help="Path to split manifest JSON",
    )
    parser.add_argument(
        "--dataset-path",
        type=Path,
        default=DEFAULT_DATASET_PATH,
        help="Path to raw dataset CSV",
    )
    parser.add_argument(
        "--evidence-path",
        type=Path,
        default=DEFAULT_EVIDENCE_PATH,
        help="Path to execution evidence JSON",
    )
    parser.add_argument(
        "--expected-dataset-sha256",
        type=str,
        default=EXPECTED_DATASET_SHA256,
        help="Expected dataset SHA-256 hash (default: official NF-UNSW-NB15-v3 hash)",
    )
    parser.add_argument(
        "--check-report-consistency",
        action="store_true",
        help="Check Markdown text consistency with companion manifest only (scope-restricted)",
    )
    parser.add_argument(
        "--verify-real-data",
        action="store_true",
        help="Verify existing report against real data and evidence without rewriting",
    )
    args = parser.parse_args()

    success = generate_smoke_report(
        report_path=args.report_path,
        manifest_path=args.manifest_path,
        artifact_path=args.artifact_path,
        split_manifest_path=args.split_manifest_path,
        dataset_path=args.dataset_path,
        evidence_path=args.evidence_path,
        check_report_consistency=args.check_report_consistency,
        verify_real_data=args.verify_real_data,
        expected_dataset_sha256=args.expected_dataset_sha256,
    )
    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
